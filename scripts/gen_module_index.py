#!/usr/bin/env python3
"""Generate docs/MODULES.md: every module of ForMathlib, QM and DFT with the title of its module docstring.

usage: gen_module_index.py           write docs/MODULES.md
       gen_module_index.py --check   exit 1 if docs/MODULES.md is out of date (used in CI)
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIBS = [('ForMathlib', 'pure mathematics (Mathlib candidates)'),
        ('QM', 'generic quantum mechanics and many-body theory (Physlib candidates)'),
        ('DFT', 'density-functional theory')]
def title(path):
    lines = open(path, encoding='utf-8').read().split('\n')
    for i, l in enumerate(lines):
        if l.lstrip().startswith('/-!'):
            rest = l.lstrip()[3:].strip()
            cand = [rest] if rest else []
            cand += lines[i + 1:i + 4]
            for c in cand:
                c = c.strip()
                if c.startswith('#'): return c.lstrip('#').strip()
                if c: return c.rstrip('-/').strip()
    return '(no module docstring)'
out = ['# Module index', '',
       'Generated by `scripts/gen_module_index.py` from the module docstrings; do not edit by hand.',
       'Folder order and layering: [`ARCHITECTURE.md`](ARCHITECTURE.md).', '']
total = 0
for lib, desc in LIBS:
    entries = []
    for dp, _, fs in os.walk(os.path.join(ROOT, lib)):
        for f in fs:
            if f.endswith('.lean'):
                p = os.path.join(dp, f)
                rel = os.path.relpath(p, ROOT)
                entries.append((os.path.dirname(rel), rel[:-5].replace(os.sep, '.'), title(p), sum(1 for _ in open(p, encoding='utf-8'))))
    lines = sum(e[3] for e in entries); total += lines
    out += [f'## `{lib}`: {desc}', '', f'{len(entries)} modules, {lines} lines.', '']
    for folder in sorted({e[0] for e in entries}):
        out += [f'### `{folder}/`', '', '| Module | Lines | Content |', '|---|---|---|']
        for _, mod, t, n in sorted(e for e in entries if e[0] == folder):
            esc = t.replace('|', r'\|')
            out.append(f'| `{mod}` | {n} | {esc} |')
        out.append('')
out += [f'Total: {total} lines of Lean.', '']
text = '\n'.join(out)
dst = os.path.join(ROOT, 'docs', 'MODULES.md')
if '--check' in sys.argv:
    cur = open(dst, encoding='utf-8').read() if os.path.exists(dst) else ''
    if cur != text:
        print('docs/MODULES.md is out of date: run scripts/gen_module_index.py'); sys.exit(1)
    print('docs/MODULES.md is up to date')
else:
    open(dst, 'w', encoding='utf-8').write(text); print(f'wrote docs/MODULES.md ({total} lines of Lean indexed)')
